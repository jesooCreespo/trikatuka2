// Generates src/i18n/available-locales.ts from the files in src/i18n/locales/.
// Runs before `npm start`, `npm run build` and `npm test`, so adding a language only takes adding
// `src/i18n/locales/<code>.json`. English is bundled separately (see src/i18n/transloco.ts).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DIR = fileURLToPath(new URL('../src/i18n/locales/', import.meta.url));
const OUT = fileURLToPath(new URL('../src/i18n/available-locales.ts', import.meta.url));

export function renderAvailableLocales(files) {
  const codes = files
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.slice(0, -'.json'.length))
    .filter((code) => code !== 'en')
    .sort();
  const loaders = codes
    .map((code) => `  '${code}': () => import('./locales/${code}.json').then((m) => m.default),`)
    .join('\n');
  return `// Generated by scripts/sync-locales.mjs from src/i18n/locales/. Do not edit: run \`npm run i18n:sync\`.
import type { Translation } from '@jsverse/transloco';

/** Lazy loaders for every language except English, which is bundled. */
export const LOCALE_LOADERS: Record<string, () => Promise<Translation>> = {
${loaders}
};
`;
}

export function currentFiles() {
  return readdirSync(DIR);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = renderAvailableLocales(currentFiles());
  let previous = '';
  try {
    previous = readFileSync(OUT, 'utf-8');
  } catch {
    // First run.
  }
  if (previous !== next) {
    writeFileSync(OUT, next);
    console.log('i18n: updated src/i18n/available-locales.ts');
  }
}
